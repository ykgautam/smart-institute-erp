-- Provide a stable income category for automatic fee-payment postings.
-- Seed existing institutes without overwriting their other category settings.

UPDATE financial_categories
SET system_key = 'FEE_COLLECTION'
WHERE transaction_type = 'INCOME'
  AND name = 'Student Fee Collection'
  AND system_key IS NULL
  AND NOT EXISTS (
    SELECT 1
    FROM financial_categories existing
    WHERE existing.institute_id = financial_categories.institute_id
      AND existing.system_key = 'FEE_COLLECTION'
);

INSERT INTO financial_categories (
    institute_id,
    name,
    transaction_type,
    description,
    system_key,
    active,
    created_at,
    created_by
)
SELECT
    i.id,
    'Student Fee Collection',
    'INCOME',
    'System category for income generated by student fee payments.',
    'FEE_COLLECTION',
    TRUE,
    CURRENT_TIMESTAMP,
    'SYSTEM'
FROM institutes i
WHERE NOT EXISTS (
    SELECT 1
    FROM financial_categories fc
    WHERE fc.institute_id = i.id
      AND fc.system_key = 'FEE_COLLECTION'
)
  AND NOT EXISTS (
    SELECT 1
    FROM financial_categories fc
    WHERE fc.institute_id = i.id
      AND fc.name = 'Student Fee Collection'
      AND fc.transaction_type = 'INCOME'
);